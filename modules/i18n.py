def get_speech_language() -> str:
    language = st.session_state.get(SPEECH_LANGUAGE_KEY, DEFAULT_LANGUAGE)
    return language if language in LANGUAGE_IDS else DEFAULT_LANGUAGE


def get_ui_language() -> str:
    language = get_speech_language()
    if language == "zh-CN":
        return "zh-Hans"
    if language == "en":
        return "en"
    return "zh-Hant"


def tr(key: str, **values: object) -> str:
    text = _TEXT[get_ui_language()].get(key)
    if text is None:
        text = _TEXT["zh-Hant"].get(key)
    if text is None:
        text = key.replace("_", " ").capitalize()
    return text.format(**values) if values else text


def get_tts_voice(language: str | None = None) -> str:
    return {
        "yue": "zh-HK-HiuGaaiNeural",
        "zh-CN": "zh-CN-XiaoxiaoNeural",
        "zh-TW": "zh-TW-HsiaoChenNeural",
        "en": "en-US-JennyNeural",
    }[language or get_speech_language()]


def get_response_language() -> str:
    return {
        "yue": "Traditional Chinese, using natural Hong Kong Cantonese phrasing",
        "zh-CN": "Simplified Chinese used in Mainland China",
        "zh-TW": "Traditional Chinese used in Taiwan",
        "en": "English",
    }[get_speech_language()]


def clear_tts_audio() -> None:
    st.session_state.pop("tts_audio_cache", None)


def localize_service_error(message: str) -> str:
    if get_ui_language() == "zh-Hant":
        return message
    safe_details = re.findall(
        r"\b(code|param|hint|model)=([A-Za-z0-9_.\-\[\]:]{1,80})",
        message,
    )
    detail_text = "; ".join(f"{field}={value}" for field, value in safe_details)
    status = re.search(r"HTTP\s+(\d{3})", message)
    if status:
        text = tr("service_http_error", status=status.group(1))
        return f"{text} ({detail_text})" if detail_text else text
    if "逾時" in message:
        return tr("service_timeout")
    if "連線" in message:
        return tr("service_connection")
    return tr("service_error")


def _select_speech_language() -> None:
    selected = st.session_state.get(LANGUAGE_OPTION_KEY)
    st.session_state[SPEECH_LANGUAGE_KEY] = LANGUAGE_BY_OPTION[selected]
    clear_tts_audio()


def render_language_selector(*, in_sidebar: bool = True) -> None:
    language = get_speech_language()
    st.session_state.setdefault(
        LANGUAGE_OPTION_KEY,
        LANGUAGE_OPTIONS[language],
    )
    container = st.sidebar if in_sidebar else st
    container.selectbox(
        tr("speech_language"),
        options=tuple(LANGUAGE_OPTIONS.values()),
        key=LANGUAGE_OPTION_KEY,
        on_change=_select_speech_language,
    )
